#!/usr/bin/env python3
"""Vector memory layout of the ZX game data for the i8080 logic (docs/PORT_PLAN.md, stage 3).

  python3 -I tools/mkl80.py

ZX $8AB7-$D713 (tile map, sprites + masks, tile graphics) moves as one block to Vector $37B7-$8413
(V = ZX - $5300, constant ZS in the asm). The room streams ($7300-$8AB6 at the ZX) are packed into
gen/rooms.asm at $2000: the floor stream raw, the wall blocks (columns 0-3 / 36-39 of room 10, rows 2-16)
as 4-byte rows, the 20 room streams in ZX0 (unpacked into a buffer when a room is built). Tables and variables above $D714 that the
logic or the Vector output uses go to islands packed from ISLAND_BASE; pointer tables inside them are
relocated. Writes src/i8080/gen/zxequ.asm (zv_XXXX EQU for every island byte), gen/zxdata.asm (the islands)
and build/l80/map.json (ZX ranges -> Vector) for tools/run80.js.
"""
import json
import os
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ZS = 0x5300
BLOCK = (0x8AB7, 0xD714)
ROOMS = 0x2000
FLOOR = (0x7808, 248)
ISLAND_BASE = 0x8414
# (lo, hi) ZX, hi exclusive
ISLANDS = [
    (0xD897, 0xDAEE),   # NEIGHBOURS, APPROACHING chars, room names, messages, stream ptrs, frame ptrs, enemy slots/table
    (0xDB44, 0xDECA),   # HUD strings, score, holes, hole edges, energy bars, animation and move tables
    (0xDEF1, 0xDEFB),   # RNG, print state
    (0xDFE1, 0xDFE3),   # saved SP / AI temp
    (0xE021, 0xE071),   # control tables
    (0xE1EC, 0xE1F4),   # control type, inputs, direction
    (0xE244, 0xE264),   # input -> action tables
    (0xE2D2, 0xE2D5),   # field flags
    (0xE37E, 0xE4DF),   # tile attributes, actor records, room, idols, counters
    (0xEB50, 0xEB68),   # recolour rooms: rows, room list, attribute pointers (Vector output)
    (0xE828, 0xE8AB),   # AI tables, projectiles, per-actor tables, current actor
    (0xEE8C, 0xEE91),   # KO / death
    (0xF0A6, 0xF0F2),   # WINNER / GAME OVER lines (Vector output)
    (0xF3A2, 0xF3A7),   # projectile hit temps
    (0xF610, 0xF62F),   # name rows, name strings
    (0xF694, 0xF699),   # rooms with tile $25 attr $2C
    (0xF91B, 0xF91D),   # room sound counter
    (0xF924, 0xF925),   # sprites flipped
    (0xF96F, 0xF97E),   # frame by enemy type, start X tables, hero X by direction
    (0xFA6E, 0xFA6F),   # read by $F9B8 for type $FF (a code byte of the ZX)
    (0xFA85, 0xFA8F),   # hero name by direction, turn animation tables
    (0xFB06, 0xFB2A),   # idol screen addresses, idol graphics
    (0xFE25, 0xFE27),   # hole edge pointer (self-modified operand at ZX)
    (0xFECA, 0xFF4D),   # attack phase per input, reach per input
    (0xFF51, 0xFF52),   # door colour (self-modified operand)
    (0xFF62, 0xFF72),   # thrown weapon graphics
]
# word tables of ZX pointers: (zx address, count)
PTRS = [(0xD9DE, 21), (0xDA0C, 50), (0xDC63, 49), (0xDDA8, 49), (0xE021, 4), (0xF61C, 5)]


def main():
    img = open(os.path.join(ROOT, 'build/zx/ram4000.bin'), 'rb').read()
    zx = lambda a: img[a - 0x4000]
    z2v = {}
    for a in range(*BLOCK):
        z2v[a] = a - ZS
    v = ISLAND_BASE
    spans = []
    for lo, hi in ISLANDS:
        spans.append([lo, hi, v])
        for a in range(lo, hi):
            z2v[a] = v + a - lo
        v += hi - lo
    end = v
    rooms_end = make_rooms(img)
    ptr = {}
    for a, n in PTRS:
        if a == 0xD9DE:
            continue
        for k in range(n):
            p = a + 2 * k
            t = zx(p) | zx(p + 1) << 8
            if t not in z2v:
                raise SystemExit(f'pointer {p:04X} -> {t:04X} not mapped')
            ptr[p] = t
    gen = os.path.join(ROOT, 'src/i8080/gen')
    os.makedirs(gen, exist_ok=True)
    os.makedirs(os.path.join(ROOT, 'build/l80'), exist_ok=True)
    with open(os.path.join(gen, 'zxequ.asm'), 'w') as f:
        f.write('; generated by tools/mkl80.py: ZX address -> Vector address\n')
        f.write(f'ZS\t\tEQU\t0x{ZS:04X}\t\t; ZX $7300-$D713 -> Vector (ZX - ZS)\n')
        f.write(f'ISLAND_BASE\tEQU\t0x{ISLAND_BASE:04X}\nISLAND_END\tEQU\t0x{end:04X}\n')
        for lo, hi, vb in spans:
            for a in range(lo, hi):
                f.write(f'zv_{a:04X}\tEQU\t0x{vb + a - lo:04X}\n')
    with open(os.path.join(gen, 'zxdata.asm'), 'w') as f:
        f.write('; generated by tools/mkl80.py: islands of ZX tables and variables (pointers relocated)\n')
        f.write('\t\t\tORG\tISLAND_BASE\n')
        for lo, hi, vb in spans:
            f.write(f'; ZX {lo:04X}-{hi - 1:04X}\n')
            a = lo
            while a < hi:
                if 0xD9DE <= a < 0xD9DE + 42:
                    n = (a - 0xD9DE) // 2
                    f.write(f'\t\t\tDW\troom_z{min(n, 19)}\t\t; {a:04X} -> поток комнаты {n} (ZX0)\n')
                    a += 2
                    continue
                if a in ptr:
                    t = ptr[a]
                    f.write(f'\t\t\tDW\t0x{z2v[t]:04X}\t\t; {a:04X} -> {t:04X}\n')
                    a += 2
                    continue
                run = []
                while a < hi and a not in ptr and not 0xD9DE <= a < 0xD9DE + 42 and len(run) < 16:
                    run.append(zx(a)); a += 1
                f.write('\t\t\tDB\t' + ','.join(f'0x{b:02X}' for b in run) + '\n')
    json.dump({'zs': ZS, 'block': list(BLOCK), 'islands': spans, 'ptrs': sorted(list(ptr) + [0xD9DE + 2 * n for n in range(21)])},
              open(os.path.join(ROOT, 'build/l80/map.json'), 'w'))
    print(f'rooms {ROOMS:04X}-{rooms_end - 1:04X} (free to {BLOCK[0] - ZS:04X}: {BLOCK[0] - ZS - rooms_end} bytes), '
          f'islands {ISLAND_BASE:04X}-{end - 1:04X} ({end - ISLAND_BASE} bytes), block {BLOCK[0] - ZS:04X}-{BLOCK[1] - ZS - 1:04X}')


def stream_len(img, p, cells, col):
    # $F64C: bytes of a stream until `cells` visible cells (columns 4..35 of 40)
    r = lambda a: img[a - 0x4000]
    s = p
    while True:
        a = r(p); p += 1
        reps = 1
        if a == 0xFF:
            reps = r(p + 1) + 1; p += 2
        for _ in range(reps):
            col += 1
            if col >= 0x28:
                col = 0
            elif 4 <= col < 0x24:
                cells -= 1
                if cells == 0:
                    return p - s


def make_rooms(img):
    zx = lambda a: img[a - 0x4000]
    gen = os.path.join(ROOT, 'src/i8080/gen')
    tmp = os.path.join(ROOT, 'build/l80/rooms')
    os.makedirs(tmp, exist_ok=True)
    out = ['; generated by tools/mkl80.py: floor stream, wall blocks, room streams in ZX0 (tools/zx0 -c)',
           '\t\t\tORG\t0x%04X' % ROOMS, 'floor_s:']
    fl = bytes(zx(FLOOR[0] + i) for i in range(FLOOR[1]))
    assert stream_len(img, FLOOR[0], 200, 0x1B) == FLOOR[1]
    out += ['\t\t\tDB\t' + ','.join(f'0x{b:02X}' for b in fl[i:i + 16]) for i in range(0, len(fl), 16)]
    for name, base in (('wall_l', 0x8134), ('wall_r', 0x8158)):
        out.append(name + ':')
        for row in range(15):
            out.append('\t\t\tDB\t' + ','.join(f'0x{zx(base + 40 * row + k):02X}' for k in range(4)))
    size = FLOOR[1] + 120
    mx = 0
    for n in range(20):
        p = zx(0xD9DE + 2 * n) | zx(0xD9DF + 2 * n) << 8
        ln = stream_len(img, p, 480, 0x27)
        mx = max(mx, ln)
        raw = os.path.join(tmp, f'r{n:02d}.raw')
        open(raw, 'wb').write(bytes(zx(p + i) for i in range(ln)))
        subprocess.run([os.path.join(ROOT, 'tools/zx0/zx0'), '-f', '-c', raw, raw + '.zx0'], check=True, capture_output=True)
        z = open(raw + '.zx0', 'rb').read()
        size += len(z)
        out.append(f'room_z{n}:\t\t\t\t; {ln} -> {len(z)}')
        out += ['\t\t\tDB\t' + ','.join(f'0x{b:02X}' for b in z[i:i + 16]) for i in range(0, len(z), 16)]
    out.append('rooms_end:')
    out.append(f'ROOMBUF_SIZE\tEQU\t{mx}\t\t; наибольший поток комнаты')
    open(os.path.join(gen, 'rooms.asm'), 'w').write('\n'.join(out) + '\n')
    return ROOMS + size


if __name__ == '__main__':
    main()
