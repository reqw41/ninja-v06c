#!/usr/bin/env python3
"""Atari Ninja sound data for the Vector (docs/MUSIC.md): src/vec/gen/music.asm.

  python3 -I tools/mksound.py

The song driver data $BD57-$BFED (from data/music/atari_bc00.bin) is placed as is at label mus_data; pointer
tables inside it (orders $BDFC/$BDFF, patterns $BE02/$BE0D, envelopes $BDC6/$BDCC) are relocated, MB =
mus_data - $BD57 turns an Atari address into a Vector one. The effect variables $2405-$2417 and $24E4-$24E9
start with the values of the Atari game (build/a8run/full/mem2250.bin, or the defaults below).
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
LO, HI = 0xBD57, 0xBFEE
PTRS = [(0xBDFC, 0xBDFF, 3), (0xBE02, 0xBE0D, 11), (0xBDC6, 0xBDCC, 6)]
# $2405-$2417 (notes, volumes, steps, bases, thud, whistle) and $24E4-$24E9 of the Atari game (mem2250)
FX_2405 = bytes.fromhex('5b0051483c352d00000000fe010110141c0000')
FX_24E4 = bytes.fromhex('000000000100')


def main():
    bc = open(os.path.join(ROOT, 'data/music/atari_bc00.bin'), 'rb').read()
    m = bytearray(0x10000)
    m[0xBC00:0xC000] = bc
    fx, e4 = FX_2405, FX_24E4
    reloc = {}
    for lo, hi, n in PTRS:
        for k in range(n):
            reloc[lo + k] = hi + k
    out = ['; generated by tools/mksound.py: Atari song data $BD57-$BFED (pointers relocated), effect variables',
           'mus_data:', 'MB\t\tEQU\tmus_data - 0x%04X' % LO]
    a = LO
    while a < HI:
        if a in reloc:                         # lo byte of a pointer: hi byte at reloc[a]
            p = m[a] | m[reloc[a]] << 8
            assert LO <= p < 0xC000, hex(p)
            out.append(f'\t\t\tDB\tlow (MB + 0x{p:04X})\t; {a:04X}')
            a += 1
            continue
        if any(a == hi + k for lo, hi, n in PTRS for k in range(n)):
            lo = next(lo for lo, hi, n in PTRS for k in range(n) if a == hi + k)
            k = a - next(hi for lo2, hi, n in PTRS if lo2 == lo)
            p = m[lo + k] | m[a] << 8
            out.append(f'\t\t\tDB\thigh (MB + 0x{p:04X})\t; {a:04X}')
            a += 1
            continue
        out.append(f'\t\t\tDB\t0x{m[a]:02X}\t\t; {a:04X}')
        a += 1
    out += ['fx_2405:', 'SV\t\tEQU\tfx_2405 - 0x2405',
            '\t\t\tDB\t' + ','.join(f'0x{b:02X}' for b in fx),
            'fx_24E4:', 'SW\t\tEQU\tfx_24E4 - 0x24E4',
            '\t\t\tDB\t' + ','.join(f'0x{b:02X}' for b in e4),
            'mus_bdbc0:\tDB\t0x%02X\t\t; $BDBC в начале' % m[0xBDBC]]
    os.makedirs(os.path.join(ROOT, 'src/vec/gen'), exist_ok=True)
    open(os.path.join(ROOT, 'src/vec/gen/music.asm'), 'w').write('\n'.join(out) + '\n')
    print(f'music data {HI - LO} bytes, fx {len(fx)}+{len(e4)}')


if __name__ == '__main__':
    main()
